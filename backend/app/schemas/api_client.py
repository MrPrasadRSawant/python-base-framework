import ipaddress
from datetime import datetime

from pydantic import Field, field_validator

from app.schemas.base import CreateSchema, ResponseSchema, UpdateSchema


def _check_ips(value: list[str] | None) -> list[str] | None:
    """Each entry must be an IP or CIDR; stored normalized (10.0.0.1 -> 10.0.0.1/32)."""
    if value is None:
        return None
    try:
        return [str(ipaddress.ip_network(v.strip(), strict=False)) for v in value]
    except ValueError as exc:
        raise ValueError(f"invalid IP / CIDR: {exc}") from None


class ApiClientCreate(CreateSchema):
    """New API client. `client_id` and `client_secret` are generated by the server."""

    name: str = Field(min_length=1, max_length=128, examples=["billing-service"])
    description: str | None = Field(None, max_length=512, examples=["Nightly invoice sync"])
    permissions: list[str] = Field(
        default_factory=list,
        max_length=500,
        description="Permission codes the client's tokens carry",
        examples=[["request_logs:read"]],
    )
    allowed_ips: list[str] | None = Field(
        None,
        max_length=100,
        description="IPs / CIDRs allowed to request tokens; `null` = any",
        examples=[["10.0.0.0/8", "203.0.113.7"]],
    )
    expires_on: datetime | None = Field(
        None, description="After this the client gets no tokens; `null` = never"
    )

    _ips = field_validator("allowed_ips")(_check_ips)


class ApiClientUpdate(UpdateSchema):
    """Fields to change; omitted fields keep their value."""

    name: str | None = Field(None, min_length=1, max_length=128)
    description: str | None = Field(None, max_length=512)
    is_active: bool | None = Field(None, description="`false` blocks new tokens immediately")
    allowed_ips: list[str] | None = Field(None, max_length=100, description="`null` = any IP")
    expires_on: datetime | None = Field(None, description="`null` = never expires")

    _ips = field_validator("allowed_ips")(_check_ips)


class ApiClientInsert(CreateSchema):
    # Internal: the row to insert.
    client_id: str = Field(max_length=64)
    secret_hash: str = Field(max_length=255)
    name: str
    description: str | None = None
    allowed_ips: list[str] | None = None
    expires_on: datetime | None = None


class ApiClientResponse(ResponseSchema):
    """A registered server-side integration. The secret is never returned here."""

    client_id: str = Field(
        description="Public identifier, sent to `/auth/token`", examples=["cli_Xy7..."]
    )
    name: str
    description: str | None
    is_active: bool = Field(description="`false` = cannot get tokens")
    allowed_ips: list[str] | None = Field(description="Normalized CIDRs; `null` = any IP")
    expires_on: datetime | None = Field(description="`null` = never expires")
    last_used_on: datetime | None = Field(description="Last time the client got a token")


class ApiClientDetailResponse(ApiClientResponse):
    """An API client with its permissions."""

    permissions: list[str] = Field(description="Permission codes put into its tokens")


class ApiClientWithSecretResponse(ApiClientDetailResponse):
    """An API client with its new secret (create and rotate-secret only)."""

    client_secret: str = Field(
        description="Shown only in this response. Store it safely; it cannot be read again."
    )
